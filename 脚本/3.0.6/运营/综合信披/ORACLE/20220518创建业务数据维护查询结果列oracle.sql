
CREATE TABLE CHB_COLUMN_MAPPING_CONFIG (
  "RESULT_ID" CHAR(64 BYTE) NOT NULL,
  "MGRTABLE_ID" NVARCHAR2(50),
  "COLUMN_ID" NVARCHAR2(50),
  "COLUMN_NAME" NVARCHAR2(100),
  "DICTCODE" NVARCHAR2(50),
  "ORDER_NO" NUMBER(10,0),
  "SHOWFLAG" CHAR(1 BYTE),
  "REAL_COLUMN_ID" NVARCHAR2(50)
);

COMMENT ON COLUMN "CHB_COLUMN_MAPPING_CONFIG"."RESULT_ID" IS '查询结果UUID';
COMMENT ON COLUMN "CHB_COLUMN_MAPPING_CONFIG"."MGRTABLE_ID" IS '业务数据维护待维护表ID';
COMMENT ON COLUMN "CHB_COLUMN_MAPPING_CONFIG"."COLUMN_ID" IS '查询结果字段名';
COMMENT ON COLUMN "CHB_COLUMN_MAPPING_CONFIG"."COLUMN_NAME" IS '查询结果字段中文名';
COMMENT ON COLUMN "CHB_COLUMN_MAPPING_CONFIG"."DICTCODE" IS '查询结果字段对应数据字典，有则填，无则不填';
COMMENT ON COLUMN "CHB_COLUMN_MAPPING_CONFIG"."ORDER_NO" IS '排序顺序';
COMMENT ON COLUMN "CHB_COLUMN_MAPPING_CONFIG"."SHOWFLAG" IS '是否前台显示，Y显示，N不显示';
COMMENT ON TABLE "CHB_COLUMN_MAPPING_CONFIG" IS '业务数据维护查询结果列';


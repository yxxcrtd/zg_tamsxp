declare
num1   number;
num2   number;
num3   number;
num4   number;
begin
SELECT COUNT(*) into num1 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'CHB_PRD_BASEINFO' and column_name = 'ERR_MSG';
SELECT COUNT(*) into num2 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'CHB_PRD_BASEINFO' and column_name = 'MANA_CATE_FIT';
SELECT COUNT(*) into num3 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'CHB_PRD_BASEINFO' and column_name = 'ISSUE_STATUS_REMARK';
SELECT COUNT(*) into num4 FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'CHB_PRD_BASEINFO' and column_name = 'FIT_CIRCLE_DAYS';
if 	num1 = 0   then execute immediate 'ALTER TABLE CHB_PRD_BASEINFO ADD ERR_MSG CLOB';
end if;
if  num2 = 0   then execute immediate 'ALTER TABLE CHB_PRD_BASEINFO ADD MANA_CATE_FIT VARCHAR2(10)';
end if;
if  num3 = 0   then execute immediate 'ALTER TABLE CHB_PRD_BASEINFO ADD ISSUE_STATUS_REMARK VARCHAR2(60)';
end if;
if  num4 = 0   then execute immediate 'ALTER TABLE CHB_PRD_BASEINFO ADD FIT_CIRCLE_DAYS NUMBER(30)';
end if;
end;
/
COMMENT ON COLUMN CHB_PRD_BASEINFO.ERR_MSG is '错误信息';
COMMENT ON COLUMN CHB_PRD_BASEINFO.MANA_CATE_FIT is '现金管理类产品-是否完全符合';
COMMENT ON COLUMN CHB_PRD_BASEINFO.ISSUE_STATUS_REMARK is '状态备注';
COMMENT ON COLUMN CHB_PRD_BASEINFO.FIT_CIRCLE_DAYS is '定期开放周期(天)';

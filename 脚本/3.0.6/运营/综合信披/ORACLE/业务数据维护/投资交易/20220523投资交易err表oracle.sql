declare
num   number;
begin
select count(*) into num from user_tables where table_name =upper('CHB_INVEST_TRADE_ERRODATA');
if   num = 1   then
          execute immediate 'drop table CHB_INVEST_TRADE_ERRODATA';
end if;
end;
/

CREATE TABLE "CHB_INVEST_TRADE_ERRODATA" (
  "DATAUUID" CHAR(36 BYTE) NOT NULL,
  "WORKFLOW_ID" VARCHAR2(20 BYTE),
  "PROD_ID" VARCHAR2(50 BYTE), 
  "REG_CODE" VARCHAR2(50 BYTE), 
  "TRADE_COUNTER" VARCHAR2(50 BYTE),
  "TRADE_CODE" VARCHAR2(50 BYTE),
  "ASSET_CODE" VARCHAR2(50 BYTE),
  "DEALDATE" DATE,
  "STATUS" VARCHAR2(50 BYTE),
  "ORG_CODE" VARCHAR2(20 BYTE),
  "DEPT_CODE" VARCHAR2(20 BYTE),
  "CREATE_DEPT"VARCHAR2(20 BYTE),
  "CREATE_USER" VARCHAR2(20 BYTE),
  "CREATE_TIME" TIMESTAMP(6),
  "UPDATE_USER" VARCHAR2(20 BYTE),
  "UPDATE_TIME" TIMESTAMP(6), 
  "ORG_DATA" CLOB,
  "ERR_MSG" CLOB
);
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."DATAUUID" IS 'uuid主键';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."TRADE_CODE" IS '行内交易编码';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."PROD_ID" IS '产品代码';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."REG_CODE" IS '产品登记编码';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."ASSET_CODE" IS '行内资产/负债编码';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."DEALDATE" IS '交易日';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."TRADE_COUNTER" IS '交易对手';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."STATUS" IS '数据状态 D	删除 A	待处理 E	有效';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."ORG_CODE" IS '机构代码';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."DEPT_CODE" IS '部门代码';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."CREATE_DEPT" IS '创建部门';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."CREATE_USER" IS '创建人';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."CREATE_TIME" IS '创建时间';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."UPDATE_USER" IS '更新人';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."UPDATE_TIME" IS '更新时间';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."ORG_DATA" IS '原始数据';
COMMENT ON COLUMN "CHB_INVEST_TRADE_ERRODATA"."ERR_MSG" IS '错误信息';
COMMENT ON TABLE "CHB_INVEST_TRADE" IS '投资交易errodata表';


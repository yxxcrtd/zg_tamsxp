declare
num   number;
begin
select count(*) into num from user_tables where table_name =upper('MST_HOLIDAY_ERRODATA');
if   num = 1   then
          execute immediate 'drop table MST_HOLIDAY_ERRODATA';
end if;
end;
/
CREATE TABLE "MST_HOLIDAY_ERRODATA" (
  "DATAUUID" CHAR(64 BYTE) NOT NULL,
  "WORKFLOW_ID" VARCHAR2(20 BYTE),
  "CALENDAR_ID" VARCHAR2(32 BYTE), 
  "IS_HOLIDAY" NUMBER(10,0), 
  
  "CDATE" DATE,
  "STATUS" VARCHAR2(50 BYTE),
  "ORG_CODE" VARCHAR2(20 BYTE),
  "DEPT_CODE" VARCHAR2(20 BYTE),
  "CREATE_USER" VARCHAR2(20 BYTE),
  "CREATE_TIME" TIMESTAMP(6),
  "UPDATE_USER" VARCHAR2(20 BYTE),
  "UPDATE_TIME" TIMESTAMP(6), 
  "ORG_DATA" CLOB,
  "ERR_MSG" CLOB
);
COMMENT ON COLUMN "MST_HOLIDAY_ERRODATA"."DATAUUID" IS 'uuid主键';
COMMENT ON COLUMN "MST_HOLIDAY_ERRODATA"."CALENDAR_ID" IS '日历编号';
COMMENT ON COLUMN "MST_HOLIDAY_ERRODATA"."IS_HOLIDAY" IS '是否节假日，0：工作日，1：节假日';

COMMENT ON COLUMN "MST_HOLIDAY_ERRODATA"."CDATE" IS '日期';

COMMENT ON COLUMN "MST_HOLIDAY_ERRODATA"."STATUS" IS '数据状态 D	删除 A	待处理 E	有效';
COMMENT ON COLUMN "MST_HOLIDAY_ERRODATA"."ORG_CODE" IS '机构代码';
COMMENT ON COLUMN "MST_HOLIDAY_ERRODATA"."DEPT_CODE" IS '部门代码';
COMMENT ON COLUMN "MST_HOLIDAY_ERRODATA"."CREATE_USER" IS '创建人';
COMMENT ON COLUMN "MST_HOLIDAY_ERRODATA"."CREATE_TIME" IS '创建时间';
COMMENT ON COLUMN "MST_HOLIDAY_ERRODATA"."UPDATE_USER" IS '更新人';
COMMENT ON COLUMN "MST_HOLIDAY_ERRODATA"."UPDATE_TIME" IS '更新时间';
COMMENT ON COLUMN "MST_HOLIDAY_ERRODATA"."ORG_DATA" IS '原始数据';
COMMENT ON COLUMN "MST_HOLIDAY_ERRODATA"."ERR_MSG" IS '错误信息';
COMMENT ON TABLE "MST_HOLIDAY_ERRODATA" IS '交易日历errodata表';

alter table MST_HOLIDAY_ERRODATA add primary key(DATAUUID);


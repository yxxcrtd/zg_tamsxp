declare
num   number;
begin
select count(*) into num from user_tables where table_name =upper('BOK_SUBJECT_ERRODATA');
if   num = 1   then
          execute immediate 'drop table BOK_SUBJECT_ERRODATA';
end if;
end;
/
CREATE TABLE "BOK_SUBJECT_ERRODATA" (
  "DATAUUID" CHAR(64 BYTE) NOT NULL,
  "WORKFLOW_ID" VARCHAR2(20 BYTE),
  "BOOKSET_ID" VARCHAR2(50 BYTE), 
  "SUBJECT_NO" VARCHAR2(32 BYTE),
	
	"SUBJECT_NAME" VARCHAR2(200 BYTE),
	"FSUBJECT_ID" VARCHAR2(32 BYTE),
	"SUBJECT_TYPE" VARCHAR2(50 BYTE),
	"SUBJECT_LEVEL" VARCHAR2(10 BYTE),
	"BAL_FLAG" VARCHAR2(32 BYTE),
 
  "STATUS" VARCHAR2(50 BYTE),
  "ORG_CODE" VARCHAR2(20 BYTE),
  "DEPT_CODE" VARCHAR2(20 BYTE),
  "CREATE_USER" VARCHAR2(20 BYTE),
  "CREATE_TIME" TIMESTAMP(6),
  "UPDATE_USER" VARCHAR2(20 BYTE),
  "UPDATE_TIME" TIMESTAMP(6), 
  "ORG_DATA" CLOB,
  "ERR_MSG" CLOB
);
COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."DATAUUID" IS 'uuid主键';
COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."BOOKSET_ID" IS '账套代码';
COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."SUBJECT_NO" IS '科目号';


COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."SUBJECT_NAME" IS '科目名称';
COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."FSUBJECT_ID" IS '上级科目号';
COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."SUBJECT_TYPE" IS '科目类型';
COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."SUBJECT_LEVEL" IS '科目级别';
COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."BAL_FLAG" IS '科目方向';

COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."STATUS" IS '数据状态 D	删除 A	待处理 E	有效';
COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."ORG_CODE" IS '机构代码';
COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."DEPT_CODE" IS '部门代码';
COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."CREATE_USER" IS '创建人';
COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."CREATE_TIME" IS '创建时间';
COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."UPDATE_USER" IS '更新人';
COMMENT ON COLUMN "BOK_SUBJECT_ERRODATA"."UPDATE_TIME" IS '更新时间';

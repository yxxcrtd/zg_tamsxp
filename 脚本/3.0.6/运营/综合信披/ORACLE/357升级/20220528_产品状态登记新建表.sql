CREATE TABLE CHB_PRD_STATUS_SUB
(
    REGIST_SEQNO           CHAR(36) not null primary key,
    PROD_ID                VARCHAR2(150),
    ISSUE_PARTY_ID         VARCHAR2(50),
    PRD_REGIST_CODE        VARCHAR2(20),
    PRD_TOTAL_AMT          NUMBER(18, 3),
    PRD_LEVERAGE           NUMBER(15, 7),
    PRD_STATUS_DATE        DATE,
    TERMID                 VARCHAR2(50),
    REMARK                 VARCHAR2(300),
    SEND_STATUS            VARCHAR2(2),
    STATUS_DATE            DATE,
    STATUS                 VARCHAR2(2),
    ERR_MSG                CLOB,
    CHB_SUBMIT_DEADLINE    DATE,
    SUBMIT_DEADLINE        DATE,
    SUBMIT_TIME            DATE,
    SUBMIT_FEEDBACK_STATUS VARCHAR2(50),
    SUBMIT_SEQ             VARCHAR2(50),
    SUBMIT_FEEDBACK_MSG    VARCHAR2(600),
    CREATE_DEPT            VARCHAR2(32),
    CREATE_USER            VARCHAR2(20),
    CREATE_TIME            TIMESTAMP(6),
    UPDATE_USER            VARCHAR2(20),
    UPDATE_TIME            TIMESTAMP(6)
);
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."REGIST_SEQNO" IS '登记序列';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."PROD_ID" IS '产品代码';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."ISSUE_PARTY_ID" IS '发行机构代码';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."PRD_REGIST_CODE" IS '产品登记编码';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."PRD_TOTAL_AMT" IS '理财产品总资产金额(元)';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."PRD_LEVERAGE" IS '理财产品杠杆率(%)';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."PRD_STATUS_DATE" IS '产品状态统计日';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."TERMID" IS '期数';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."REMARK" IS '备注';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."SEND_STATUS" IS '报送状态';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."STATUS_DATE" IS '数据日期';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."STATUS" IS '数据状态';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."ERR_MSG" IS '错误信息';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."CHB_SUBMIT_DEADLINE" IS '报送截止日';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."SUBMIT_DEADLINE" IS '行内报送截止日';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."SUBMIT_TIME" IS '报送日期';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."SUBMIT_FEEDBACK_STATUS" IS '反馈状态';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."SUBMIT_SEQ" IS '报送流水号';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."SUBMIT_FEEDBACK_MSG" IS '反馈信息';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."CREATE_DEPT" IS '创建部门';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."CREATE_USER" IS '创建人';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."CREATE_TIME" IS '创建时间';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."UPDATE_USER" IS '更新人';
COMMENT ON COLUMN "CHB_PRD_STATUS_SUB"."UPDATE_TIME" IS '更新时间';
COMMENT ON TABLE CHB_PRD_STATUS_SUB IS '产品状态登记表';
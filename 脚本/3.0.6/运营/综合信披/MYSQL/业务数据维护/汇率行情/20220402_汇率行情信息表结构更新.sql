
DELIMITER ??
DROP PROCEDURE IF EXISTS schema_change??
CREATE PROCEDURE schema_change()
BEGIN
IF NOT EXISTS (SELECT * FROM information_schema.columns WHERE table_schema = DATABASE()  AND table_name = 'MST_EXCHARGE_QUOTE' AND column_name = 'ERR_MSG') THEN

ALTER TABLE MST_EXCHARGE_QUOTE ADD ERR_MSG TEXT COMMENT '错误信息';

END IF;
IF NOT EXISTS (SELECT * FROM information_schema.columns WHERE table_schema = DATABASE()  AND table_name = 'MST_EXCHARGE_QUOTE' AND column_name = 'DATA_SOURCE') THEN

ALTER TABLE MST_EXCHARGE_QUOTE ADD DATA_SOURCE VARCHAR(50) COMMENT '数据来源';

END IF;
IF NOT EXISTS (SELECT * FROM information_schema.columns WHERE table_schema = DATABASE()  AND table_name = 'MST_EXCHARGE_QUOTE' AND column_name = 'STATUS') THEN

ALTER TABLE MST_EXCHARGE_QUOTE ADD STATUS VARCHAR(20) COMMENT '数据状态';

END IF;

END??
DELIMITER ;

CALL schema_change();
(
    SEQNO          CHAR(36)      NOT NULL
        CONSTRAINT LIQUIDITY_RISK_INFO_PK PRIMARY KEY,
    PROD_ID        VARCHAR2(150),
    REG_CODE       VARCHAR2(50),
    SOLUTIONS      VARCHAR2(4),
    OCCUR_DATE     DATE,
    REPLY_DATE     DATE,
    DESCRIBED      VARCHAR2(256),
    DISPOSE_RESULT VARCHAR2(256),
    REMARK         VARCHAR2(256),
    ERR_MSG        CLOB,
    DATA_SOURCE    VARCHAR2(2),
    STATUS         VARCHAR2(2),
    ORG_CODE       VARCHAR2(20),
    DEPT_CODE      VARCHAR2(20),
    CREATE_USER    VARCHAR2(20),
    CREATE_TIME    TIMESTAMP(6),
    UPDATE_USER    VARCHAR2(20),
    UPDATE_TIME    TIMESTAMP(6)
);
